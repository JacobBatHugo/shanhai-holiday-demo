// @vitest-environment jsdom
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeAll, describe, expect, it, vi } from 'vitest'
import { ConfigProvider } from 'antd'
import Demo from './Demo'
import { captureAnnotation, exportAnnotations } from './review'

beforeAll(() => {
  window.matchMedia = vi.fn().mockImplementation(query => ({ matches: false, media: query, onchange: null, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {}, dispatchEvent() { return true } }))
  Element.prototype.scrollIntoView = vi.fn()
})
afterEach(() => { cleanup(); vi.useRealTimers() })
const renderDemo = () => render(<ConfigProvider theme={{ token: { motion: false } }}><Demo /></ConfigProvider>)

describe('revised holiday preview', () => {
  it('snapshots saved and unsaved settings separately with a stable save target across reopening', async () => {
    renderDemo()
    fireEvent.click(screen.getByRole('button', { name: '课表设置' }))
    const capture = (id: number) => captureAnnotation(screen.getByRole('button', { name: '保存设置' }), 'test', 'test', id)
    const initial = capture(1)
    expect(initial.target.selector).toBe('[data-review-id="settings-save"]')
    expect(initial.settingsState).toEqual({ savedEnabled: false, draftEnabled: false })
    fireEvent.click(screen.getByRole('checkbox'))
    const edited = capture(2)
    expect(edited.settingsState).toEqual({ savedEnabled: false, draftEnabled: true })
    expect(edited.target.selector).toBe(initial.target.selector)
    expect(document.querySelectorAll(initial.target.selector)).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: '关闭' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: '课表设置' }))
    const reopened = capture(3)
    expect(reopened.target.selector).toBe(initial.target.selector)
    expect(reopened.settingsState).toEqual(initial.settingsState)
    expect(edited.settingsState).toEqual({ savedEnabled: false, draftEnabled: true })
    const exported = exportAnnotations([initial, edited, reopened])
    expect(exported).toContain('设置已保存：按节假日自动调整=关闭')
    expect(exported).toContain('当前表单：按节假日自动调整=开启（有未保存更改）')
    expect(exported).toContain('当前表单：按节假日自动调整=关闭（与已保存一致）')
    fireEvent.click(screen.getByRole('checkbox'))
    fireEvent.click(screen.getByRole('button', { name: '保存设置' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: '课表设置' }))
    const saved = capture(4)
    expect(saved.settingsState).toEqual({ savedEnabled: true, draftEnabled: true })
    fireEvent.click(screen.getByRole('checkbox'))
    expect(capture(5).settingsState).toEqual({ savedEnabled: true, draftEnabled: false })
  })
  it('annotates inside settings without toggling or closing the form, then resumes normal interaction', async () => {
    renderDemo()
    fireEvent.click(screen.getByRole('button', { name: '验收模式' }))
    fireEvent.click(screen.getByRole('button', { name: '课表设置' }))
    fireEvent.click(screen.getByRole('button', { name: '选取元素' }))
    fireEvent.click(screen.getByRole('checkbox', { name: '按节假日自动调整' }))
    fireEvent.change(screen.getByLabelText('你的原话'), { target: { value: '开关测试' } })
    fireEvent.click(screen.getByRole('button', { name: '保存批注' }))
    await waitFor(() => expect(screen.queryByLabelText('你的原话')).toBeNull())
    expect(screen.getByRole('checkbox')).toHaveProperty('checked', false)
    expect(screen.getByRole('dialog', { name: '课表设置' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: '退出验收' }))
    fireEvent.click(screen.getByRole('checkbox'))
    expect(screen.getByRole('checkbox')).toHaveProperty('checked', true)
    fireEvent.click(screen.getByRole('button', { name: '关闭' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
  })
  it('drops a closed makeup draft and keeps the last saved source when reopened', async () => {
    renderDemo()
    fireEvent.change(screen.getByLabelText('预览场景'), { target: { value: 'makeup' } })
    fireEvent.click(screen.getByRole('button', { name: '设置补课' }))
    fireEvent.click(screen.getByRole('button', { name: '周二' }))
    fireEvent.click(screen.getByRole('button', { name: '关闭' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: '设置补课' }))
    expect(screen.queryByRole('region', { name: '补课预览' })).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '周二' }))
    fireEvent.click(screen.getByRole('button', { name: '保存补课' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: /补 10\/06 的课/ }))
    fireEvent.click(screen.getByRole('button', { name: '周五' }))
    fireEvent.click(screen.getByRole('button', { name: '关闭' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: /补 10\/06 的课/ }))
    expect(screen.getByRole('button', { name: '周二' }).getAttribute('aria-pressed')).toBe('true')
    expect(screen.getByRole('button', { name: '周五' }).getAttribute('aria-pressed')).toBe('false')
  })
  it('discards settings on cancel but applies them only on save', async () => {
    renderDemo()
    fireEvent.click(screen.getByRole('button', { name: '课表设置' }))
    fireEvent.click(screen.getByRole('checkbox', { name: '按节假日自动调整' }))
    fireEvent.click(screen.getByRole('button', { name: /^取\s*消$/ }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: '课表设置' }))
    expect(screen.getByRole('checkbox')).toHaveProperty('checked', false)
    fireEvent.click(screen.getByRole('checkbox'))
    fireEvent.click(screen.getByRole('button', { name: '保存设置' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: '课表设置' }))
    expect(screen.getByRole('checkbox')).toHaveProperty('checked', true)
  })
  it('returns focus to the restored makeup action after undo replaces its trigger', async () => {
    renderDemo()
    fireEvent.change(screen.getByLabelText('预览场景'), { target: { value: 'makeup' } })
    fireEvent.click(screen.getByRole('button', { name: '设置补课' }))
    fireEvent.click(screen.getByRole('button', { name: '周二' }))
    fireEvent.click(screen.getByRole('button', { name: '保存补课' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    fireEvent.click(screen.getByRole('button', { name: '撤销' }))
    await waitFor(() => expect(document.activeElement).toBe(screen.getByRole('button', { name: '设置补课' })))
  })
  it('automatically clears restoration feedback after five seconds', () => {
    vi.useFakeTimers()
    renderDemo()
    fireEvent.change(screen.getByLabelText('预览场景'), { target: { value: 'holiday' } })
    fireEvent.click(screen.getByRole('button', { name: '10月1日 周四，国庆节，恢复上课' }))
    fireEvent.click(screen.getByRole('button', { name: /仅恢复当天/ }))
    expect(screen.getByText('10月1日已恢复上课')).toBeTruthy()
    act(() => vi.advanceTimersByTime(5000))
    expect(screen.queryByText('10月1日已恢复上课')).toBeNull()
  })
  it('restores one day without offering a holiday reapply or restoration undo', async () => {
    renderDemo()
    fireEvent.change(screen.getByLabelText('预览场景'), { target: { value: 'holiday' } })
    fireEvent.click(screen.getByRole('button', { name: '10月1日 周四，国庆节，恢复上课' }))
    fireEvent.click(await screen.findByRole('button', { name: /仅恢复当天/ }))
    await waitFor(() => expect(screen.getByRole('button', { name: /10月1日 周四 机械设计基础/ })).toBeTruthy())
    expect(screen.getByRole('button', { name: '10月2日 周五，国庆节，恢复上课' })).toBeTruthy()
    expect(screen.queryByRole('button', { name: '重新放假' })).toBeNull()
    expect(screen.queryByRole('button', { name: '撤销' })).toBeNull()
  })
  it('cancels a holiday restoration without changing the timetable', async () => {
    renderDemo()
    fireEvent.change(screen.getByLabelText('预览场景'), { target: { value: 'holiday' } })
    fireEvent.click(screen.getByRole('button', { name: '10月1日 周四，国庆节，恢复上课' }))
    fireEvent.click(screen.getByRole('button', { name: '取消' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).toBeNull())
    expect(screen.queryByRole('button', { name: /10月1日 周四 机械设计基础/ })).toBeNull()
    expect(screen.getByRole('button', { name: '10月1日 周四，国庆节，恢复上课' })).toBeTruthy()
  })
  it('shows all seven statutory holiday designs without changing the active scenario', () => {
    renderDemo()
    fireEvent.click(screen.getByRole('button', { name: '节日卡片' }))
    for (const name of ['元旦', '春节', '清明节', '劳动节', '端午节', '中秋节', '国庆节']) expect(screen.getByText(name, { exact: true })).toBeTruthy()
    expect(screen.getByLabelText('预览场景')).toHaveProperty('value', 'initial')
  })
})
